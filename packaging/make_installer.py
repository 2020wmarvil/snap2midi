"""Build the downloading installer: dist/installer/ and dist/snap2midi-installer-<version>.zip

    .venv\\Scripts\\python packaging/make_installer.py

The installer package is small (the snap2midi wheel plus scripts). At install
time it downloads everything else from the official sources, pinned to the exact
versions tested here and checked against SHA-256 hashes:
  - Python embeddable runtime (python.org)
  - pip, and every Python package (PyPI), via lock files with --require-hashes
  - NVIDIA CUDA/cuDNN packages (PyPI) only when the PC has an NVIDIA GPU
  - homr and OCR models (their own release downloads)
  - Audiveris (its GitHub release MSI, unpacked without a system install)
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "packaging" / "cache"
OUT = ROOT / "dist" / "installer"

PY_VERSION = "3.11.4"
PY_URL = f"https://www.python.org/ftp/python/{PY_VERSION}/python-{PY_VERSION}-embed-amd64.zip"
AUDIVERIS_VERSION = "5.11.0"
AUDIVERIS_URL = (f"https://github.com/Audiveris/audiveris/releases/download/{AUDIVERIS_VERSION}/"
                 f"Audiveris-{AUDIVERIS_VERSION}-windowsConsole-x86_64.msi")
PIP_VERSION = "26.0.1"


def log(msg: str) -> None:
    print(f"[installer] {msg}", flush=True)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(url: str) -> Path:
    dest = CACHE / Path(url).name
    if not dest.exists():
        log(f"downloading {url}")
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(dest.suffix + ".part")
        urllib.request.urlretrieve(url, tmp)
        tmp.rename(dest)
    return dest


def pypi_file(name: str, version: str, filename_re: str) -> dict:
    data = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json"))
    for u in data["urls"]:
        if re.fullmatch(filename_re, u["filename"]):
            return {"url": u["url"], "file": u["filename"], "sha256": u["digests"]["sha256"]}
    raise SystemExit(f"{name} {version}: no file matching {filename_re}")


def wheel_name_version(filename: str) -> tuple[str, str]:
    name, version = filename.split("-")[:2]
    return name.replace("_", "-").lower(), version


def main() -> None:
    if sys.version_info[:2] != (3, 11):
        sys.exit("run with Python 3.11 (the project .venv)")
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    log("building the snap2midi wheel")
    subprocess.run([sys.executable, "-m", "pip", "wheel", "--no-deps", "-q", "-w", str(OUT), str(ROOT)], check=True)
    wheel = next(OUT.glob("snap2midi-*.whl"))
    version = wheel_name_version(wheel.name)[1]

    log("resolving pinned dependencies for Windows x64, Python 3.11")
    wheels = CACHE / "wheels"
    if wheels.exists():
        shutil.rmtree(wheels)
    subprocess.run([sys.executable, "-m", "pip", "download", "-q", "--only-binary", ":all:",
                    "--platform", "win_amd64", "--python-version", "3.11", "--implementation", "cp",
                    "--abi", "cp311", "-d", str(wheels), f"{wheel}[cuda]"], check=True)
    core, gpu = [], []
    for f in sorted(wheels.glob("*.whl")):
        name, ver = wheel_name_version(f.name)
        if name == "snap2midi":
            continue
        line = f"{name}=={ver} --hash=sha256:{sha256(f)}"
        (gpu if name.startswith("nvidia-") else core).append(line)
    header = "# Generated by packaging/make_installer.py. Installed with --require-hashes --no-deps.\n"
    (OUT / "requirements-core.txt").write_text(header + "\n".join(core) + "\n")
    (OUT / "requirements-gpu.txt").write_text(header + "\n".join(gpu) + "\n")
    log(f"{len(core)} core packages, {len(gpu)} GPU packages")

    log("pinning the Python runtime, pip and Audiveris")
    py_zip = fetch(PY_URL)
    msi = fetch(AUDIVERIS_URL)
    manifest = {
        "snap2midi": version,
        "wheel": wheel.name,
        "python": {"url": PY_URL, "sha256": sha256(py_zip)},
        "pip": pypi_file("pip", PIP_VERSION, r"pip-.*-py3-none-any\.whl"),
        "audiveris": {"url": AUDIVERIS_URL, "sha256": sha256(msi), "version": AUDIVERIS_VERSION},
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

    for f in ("install.ps1", "install.cmd"):
        text = (ROOT / "packaging" / "installer" / f).read_text(encoding="utf-8")
        (OUT / f).write_text(text, encoding="utf-8", newline="\r\n")  # Windows line endings
    shutil.copy2(ROOT / "skill" / "snap2midi" / "SKILL.md", OUT / "SKILL.md")
    shutil.copy2(ROOT / "packaging" / "licenses" / "Audiveris-LICENSE.txt", OUT / "Audiveris-LICENSE.txt")

    zpath = OUT.parent / f"snap2midi-installer-{version}.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.iterdir()):
            z.write(f, f"snap2midi-installer-{version}/{f.name}")
    log(f"done: {zpath} ({zpath.stat().st_size / 1e3:.0f} KB)")


if __name__ == "__main__":
    main()
